// Operadores Logicos

// AND (&&) OR (||) NOT (!)

//Operador AND (&&)
//Regresa true solo si ambas expresiones son verdades.
console.log(true && true);
console.log(true && false);
console.log(false && true);
console.log(false && false);

// Operador OR (||)
// Regresa true si almenos una de las expresiones es verdadera.
console.log(true || true);
console.log(true || false);
console.log(false || true);
console.log(false || false);

// Operador NOT (!)
console.log(!true);
console.log(!false);
